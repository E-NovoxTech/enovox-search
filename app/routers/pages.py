def template_exists(template_name: str) -> bool:
    """Return whether a page template is installed in the configured template directory."""
    try:
        templates.env.get_template(template_name)
        return True
    except TemplateNotFound:
        return False


def render_page(
    request: Request,
    template_name: str,
    context: Optional[Dict[str, Any]] = None,
):
    """Render a page, returning a clean 404 when its template is not deployed yet."""
    try:
        templates.env.get_template(template_name)
    except TemplateNotFound as exc:
        raise HTTPException(
            status_code=404,
            detail=f"Page template '{template_name}' was not found.",
        ) from exc

    return templates.TemplateResponse(
        request=request,
        name=template_name,
        context=context or {},
    )


